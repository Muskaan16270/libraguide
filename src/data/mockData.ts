// Build seats for a room
function buildSeats(
  roomId: string,
  total: number,
  occupiedPattern: number[],
  reservedPattern: number[] = [],
  unavailablePattern: number[] = [],
): Seat[] {
  const seats: Seat[] = [];
  const memberPriorityCount = Math.max(1, Math.floor(total * 0.1));
  for (let i = 1; i <= total; i++) {
    let state: SeatState = 'available';
    if (occupiedPattern.includes(i)) state = 'occupied';
    else if (reservedPattern.includes(i)) state = 'reserved';
    else if (unavailablePattern.includes(i)) state = 'unavailable';
    seats.push({
      id: `${roomId}-s${i}`,
      roomId,
      number: i,
      state,
      hasPower: i % 3 === 0,
      nearWindow: i % 10 === 1 || i % 10 === 0,
      isMemberPriority: i <= memberPriorityCount,
    });
  }
  return seats;
}

export function getMemberPriorityCount(totalSeats: number): number {
  return Math.max(1, Math.floor(totalSeats * 0.1));
}

